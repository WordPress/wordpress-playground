#!/usr/bin/env node

// Materialize TypeDoc summaries for the handbook's Markdown importer.
const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');

const siteDir = path.resolve(__dirname, '..');
const sourceFile = path.join(
	siteDir,
	'docs',
	'developers',
	'06-apis',
	'javascript-api',
	'03-playground-api-client.md'
);
const outputFile = path.join(
	siteDir,
	'static',
	'handbook',
	'playground-api-client.md'
);
const api = require(path.join(siteDir, 'src', 'model.json'));

let markdown = fs.readFileSync(sourceFile, 'utf8');
const importLine =
	"import TSDocstring from '@site/src/components/TSDocstring';\n";
if (!markdown.includes(importLine)) {
	throw new Error('TSDocstring import not found in API Client page');
}
markdown = markdown.replace(importLine, '');

for (const method of ['run', 'request']) {
	const component = `<TSDocstring path={[ "@wp-playground/client", "PlaygroundClient", "${method}" ]} />`;
	if (!markdown.includes(component)) {
		throw new Error(
			`TSDocstring for ${method} not found in API Client page`
		);
	}
	const member = getMember(
		'@wp-playground/client',
		'PlaygroundClient',
		method
	);
	let summary = member.signatures?.[0]?.comment?.summary || [];
	if (!summary.length && method === 'run') {
		// The client's @inheritDoc target is unresolved in TypeDoc's JSON output.
		summary =
			getMember('@php-wasm/universal', 'PHP', method).signatures?.[0]
				?.comment?.summary || [];
	}
	if (!summary.length) {
		throw new Error(`No TypeDoc summary for ${method}`);
	}
	let text = summary
		.map((part) => part.text)
		.join('')
		.trim()
		.replace(/^(#{1,5})(?= )/gm, '$1#');
	if (method === 'run') {
		text = text.replace(/\bphp\.(run|writeFile)\(/g, 'client.$1(');
	}
	markdown = markdown.replace(component, text);
}

markdown = markdown.replace(
	/^---\n([\s\S]*?)\n---\n/,
	'---\n$1\n---\n\n<!-- Generated by bin/generate-handbook-api-client.js. Do not edit directly. -->\n'
);
fs.mkdirSync(path.dirname(outputFile), { recursive: true });
writeFormattedMarkdown(markdown).catch((error) => {
	console.error(error);
	process.exitCode = 1;
});

async function writeFormattedMarkdown(content) {
	const options = await prettier.resolveConfig(outputFile);
	const formatted = await prettier.format(content, {
		...options,
		filepath: outputFile,
		printWidth: 100,
	});
	fs.writeFileSync(outputFile, formatted);
}

function getMember(moduleName, className, memberName) {
	const module = api.children.find((entry) => entry.name === moduleName);
	const parent = module?.children?.find((entry) => entry.name === className);
	const member = parent?.children?.find((entry) => entry.name === memberName);
	if (!member) {
		throw new Error(
			`TypeDoc member ${moduleName}.${className}.${memberName} not found`
		);
	}
	return member;
}
