#!/usr/bin/env node

// Generate the complete Markdown Steps page consumed by the handbook importer.
// Run after TypeDoc has written src/model.json.
const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');

const siteDir = path.resolve(__dirname, '..');
const outputFile = path.join(
	siteDir,
	'static',
	'handbook',
	'blueprints-steps.md'
);
const api = require(path.join(siteDir, 'src', 'model.json'));
const blueprints = api.children.find(
	(entry) => entry.name === '@wp-playground/blueprints'
);
const excluded = new Set([
	'CompiledStep',
	'CompiledV1Step',
	'GenericStep',
	'Step',
]);
const steps = blueprints.children
	.filter((entry) => entry.name.endsWith('Step'))
	.filter((entry) => !excluded.has(entry.name) && !entry.flags?.isPrivate)
	.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const lines = [
	'---',
	'slug: /blueprints/steps',
	'description: The main API reference for the steps property.',
	'---',
	'',
	'# Steps',
	'',
	'The `steps` property of a Blueprint is an array of steps to run. For example, this Blueprint logs the user in as an admin:',
	'',
	'```json',
	JSON.stringify(
		{ steps: [{ step: 'login', username: 'admin', password: 'password' }] },
		null,
		4
	),
	'```',
	'',
	'Each step is an object that contains a `step` property that specifies the type of step to run. The rest of the properties depend on the type of step. Learn each step type below.',
	'',
	'- [Resources References](/blueprints/steps/resources) describe external files in Blueprints.',
	'- Some steps have a shorthand version. See [Shorthands](/blueprints/steps/shorthands).',
	'- See [API Consistency](/blueprints/steps/api-consistency) for the Blueprint API and Function API.',
	'- The [WordPress Playground Step Library](https://akirk.github.io/playground-step-library/#) offers a visual Blueprint editor.',
	'',
];

for (const entry of steps) {
	const properties =
		entry.children || entry.type?.declaration?.children || [];
	const step = properties.find((property) => property.name === 'step')?.type
		?.value;
	if (!step) {
		throw new Error(`No step ID found for ${entry.name}`);
	}
	lines.push(
		`<a id="${entry.name}"></a>`,
		'',
		`## ${step}`,
		'',
		summary(entry.comment),
		''
	);
	const parameters = properties.filter(
		(property) => property.name !== 'step'
	);
	lines.push('### Parameters', '');
	for (const property of parameters) {
		const type = property.type?.name ? ` (${property.type.name})` : '';
		const description = summary(property.comment).replace(/\n/g, '\n  ');
		lines.push(
			`- **${property.name}**${type}${description ? ` – ${description}` : ''}`
		);
	}
	lines.push('');
	const examples = entry.comment?.blockTags
		?.filter((tag) => tag.tag === '@example')
		.map((tag) => cleanExample(tag.content?.[0]?.text))
		.filter(Boolean);
	if (examples?.length) {
		lines.push('### Blueprint API example', '');
		for (const example of examples) {
			lines.push('```json', example, '```', '');
		}
	}
	const fn = blueprints.children.find(
		(candidate) =>
			candidate.kind === 64 &&
			candidate.signatures?.[0]?.parameters?.[0]?.type?.name ===
				'UniversalPHP' &&
			candidate.signatures?.[0]?.parameters?.[1]?.type?.typeArguments?.[0]
				?.name === entry.name
	);
	if (!fn) {
		throw new Error(`No Blueprint function found for ${entry.name}`);
	}
	lines.push(
		'### Function API',
		'',
		`\`${fn.name}(playground, args, progress)\``,
		''
	);
	const jsonExample = examples?.map(parseExample).find(Boolean);
	if (jsonExample) {
		delete jsonExample.step;
		const args = JSON.stringify(jsonExample, null, 4);
		lines.push(
			'```ts',
			`import { ${fn.name} } from '@wp-playground/blueprints';`,
			'',
			`${fn.name}(playground, ${args}, progress);`,
			'```',
			''
		);
	}
	if (entry !== steps[steps.length - 1]) {
		lines.push('---', '');
	}
}

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
const markdown = `${lines.slice(0, 4).join('\n')}\n\n<!-- Generated by bin/generate-handbook-steps.js. Do not edit directly. -->\n${lines.slice(4).join('\n').trimEnd()}\n`;
writeFormattedMarkdown(
	markdown.replace(/[ \t]+$/gm, '').replace(/^ +\t/gm, '\t')
).catch((error) => {
	console.error(error);
	process.exitCode = 1;
});

async function writeFormattedMarkdown(content) {
	const options = await prettier.resolveConfig(outputFile);
	const formatted = await prettier.format(content, {
		...options,
		filepath: outputFile,
		printWidth: 100,
	});
	fs.writeFileSync(outputFile, formatted);
}

function summary(comment) {
	return (comment?.summary || [])
		.map((part) =>
			part.kind === 'code'
				? `\`${part.text.replace(/^`|`$/g, '')}\``
				: part.text
		)
		.join('')
		.trim();
}

function cleanExample(example) {
	return example
		?.trim()
		.replace(/^```(?:ts|json)\s*/, '')
		.replace(/\s*```$/, '')
		.trim()
		.replace(/^<code>\s*/, '')
		.replace(/\s*<\/code>$/, '')
		.trim();
}

function parseExample(example) {
	try {
		return JSON.parse(example);
	} catch {
		return null;
	}
}
