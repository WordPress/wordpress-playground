<?php
// Set error reporting
error_reporting(E_ALL);
ini_set('display_errors', 0);

define('MAX_REQUEST_SIZE', 1 * 1024 * 1024); // 1MB
define('MAX_RESPONSE_SIZE', 100 * 1024 * 1024); // 100MB
require_once __DIR__ . '/cors-proxy-functions.php';

$config_file = __DIR__ . '/cors-proxy-config.php';
if (file_exists($config_file)) {
    require_once $config_file;
}

$server_host = $_SERVER['HTTP_HOST'] ?? '';
$origin = $_SERVER['HTTP_ORIGIN'] ?? '';

// Both allowed and denied origins must vary, including preflight and error responses.
header('Vary: Origin', false);
header('Cross-Origin-Resource-Policy: cross-origin');

if (should_respond_with_cors_headers($server_host, $origin)) {
    // On the dev server, the browser doesn't send an Origin header
    // (same-origin request via Vite proxy), so fall back to wildcard.
    $allow_origin = (is_local_dev_server() && empty($origin)) ? '*' : $origin;
    header('Access-Control-Allow-Origin: ' . $allow_origin);
    header('Access-Control-Allow-Credentials: true');
    header('Access-Control-Allow-Methods: GET, HEAD, POST, OPTIONS');
    header('Access-Control-Allow-Headers: Accept, Authorization, Content-Type, git-protocol, Range, wp_blog, wp_install, x-cors-proxy-allowed-request-headers, x-cors-proxy-content-type, x-cors-proxy-range');
    // Identify this response as coming from the legitimate CORS proxy.
    // Network firewalls may intercept requests and return error responses
    // without this header, allowing clients to detect interference.
    header('X-Playground-Cors-Proxy: true');
    // These are not CORS-safelisted response headers, so browsers hide them
    // from range request callers by default. ETag lets callers detect a
    // target that changed between two range reads.
    header('Access-Control-Expose-Headers: X-Playground-Cors-Proxy, Content-Range, Accept-Ranges, ETag');
}
if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    header("Allow: GET, HEAD, POST, OPTIONS");
    exit;
}

// Handle only GET, HEAD, and POST requests
if (!in_array($_SERVER['REQUEST_METHOD'], ['GET', 'HEAD', 'POST'], true)) {
    http_response_code(405);
    echo "Method Not Allowed";
    exit;
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_SERVER['CONTENT_LENGTH'] ?? 0) >= MAX_REQUEST_SIZE) {
    http_response_code(413);
    echo "Request Entity Too Large";
    exit;
}

// @TODO: Consider redirecting to the target URL if presented with a non-browser user agent.

if (function_exists('playground_cors_proxy_maybe_rate_limit')) {
    playground_cors_proxy_maybe_rate_limit();
} else if (
    !getenv('PLAYGROUND_CORS_PROXY_DISABLE_RATE_LIMIT') && (
        !defined('PLAYGROUND_CORS_PROXY_DISABLE_RATE_LIMIT') ||
        !PLAYGROUND_CORS_PROXY_DISABLE_RATE_LIMIT
    )
) {
    http_response_code(503);
    echo "Server needs to configure rate-limiting.";
    exit;
}

// Get the full target URL from the request path
$targetUrl = get_target_url($_SERVER);
if(!$targetUrl) {
    http_response_code(400);
    echo "Bad Request\n\nNo URL provided";
    exit;
}

try {
    $resolved = url_validate_and_resolve($targetUrl);
} catch (CorsProxyException $e) {
    http_response_code(400);
    echo "Bad Request\n\n" . $e->getMessage();
    exit;
}

define(
    'CURRENT_SCRIPT_URI',
    get_current_script_uri($targetUrl, $_SERVER['REQUEST_URI'])
);

$ch = curl_init($targetUrl);

$is_chunked_response = false;
// Only headers are buffered. Bodies continue to stream through the write callback.
$pending_response_headers = [];
$in_interim_response = false;
$response_headers_complete = false;
$has_transfer_encoding = false;

/**
 * Replaces the target's response with an error response from the proxy.
 *
 * Call only before any output has started, while headers_sent() is false.
 * The target's status and headers may be queued by then. The error response
 * keeps only the headers queued before the target was contacted.
 *
 * Every target header goes, not just the ones describing its body. An error
 * generated by the proxy must not carry headers from the response it
 * replaces: Location, Vary, or Expires would describe a response that never
 * arrived, and a relayed Transfer-Encoding would frame the error message as
 * chunks. Removing everything also means no list of headers to maintain as
 * the proxy relays new ones.
 *
 * The proxy's own headers are restored from a snapshot rather than rebuilt,
 * so headers set by the deployment, e.g. in cors-proxy-config.php or an
 * auto_prepend_file, survive too.
 */
function replace_response_with_error($status_code, $message) {
    global $is_chunked_response, $proxy_headers;
    header_remove();
    foreach ($proxy_headers as $header) {
        header($header, false);
    }
    // The error message has no proxy-owned chunked framing.
    $is_chunked_response = false;
    http_response_code($status_code);
    send_response_chunk($message);
}

function send_response_chunk($data) {
    if (should_send_as_chunked_response()) {
        // We need to manually chunk the response when running in the PHP
        // built-in server. It won't handle that for us.
        echo sprintf("%s\r\n%s\r\n", dechex(strlen($data)), $data);
    } else {
        // When running behind an Apache or Nginx or another webserver,
        // it will handle the chunking for us. Manually sending the chunk
        // header, \r\n separator, body, and \r\n trailer isn't just
        // unnecessary, but it would actually include those bytes in the
        // response body.
        echo $data;
    }
    @ob_flush();
    @flush();
}

/**
 * We need to manually chunk the response when running the PHP
 * dev server AND the proxy has generated its own chunked framing.
 *
 * Apache, Nginx, etc. will handle the chunking for us.
 */
function should_send_as_chunked_response() {
    global $is_chunked_response;
    return $is_chunked_response && php_sapi_name() === 'cli-server';
}

try {
    set_curl_destination($ch, $resolved);
} catch (CorsProxyException $e) {
    http_response_code(500);
    echo "Internal Server Error\n\n" . $e->getMessage();
    exit;
}

$allHeaders = getallheaders();
$connection_headers = connection_header_names(kv_headers_to_curl_format($allHeaders));

// If the browser wrapped Content-Type to prevent PHP from consuming
// multipart/form-data bodies, extract the original value to restore
// it for the outgoing request. PHP automatically parses
// multipart/form-data into $_POST/$_FILES, emptying php://input and
// making it impossible for the proxy to forward the raw body.
$originalContentType = null;
foreach ($allHeaders as $name => $value) {
    if (strcasecmp($name, 'X-Cors-Proxy-Content-Type') === 0) {
        // Reject values containing CR/LF to prevent header injection.
        if (!preg_match('/[\r\n]/', $value)) {
            $originalContentType = $value;
        }
        break;
    }
}

// WORKAROUND: As of 2026-09-26, the WP Cloud front end of the production
// deployment strips the Range header before the request reaches PHP, so
// clients may send the same value as X-Cors-Proxy-Range instead. Remove
// this, the matching Access-Control-Allow-Headers entry, and the README
// note once Range reaches this script on WP Cloud.
$tunneledRange = null;
foreach ($allHeaders as $name => $value) {
    if (strcasecmp($name, 'X-Cors-Proxy-Range') === 0) {
        // Ignore empty values, which curl would treat as removing Range.
        // Reject values containing CR/LF to prevent header injection.
        $value = trim($value);
        if ($value !== '' && !preg_match('/[\r\n]/', $value)) {
            $tunneledRange = $value;
        }
        break;
    }
}
// Range takes priority. When both headers arrive, they must match:
// forwarding either one would silently ignore the other.
$clientRange = trim(array_change_key_case($allHeaders, CASE_LOWER)['range'] ?? '');
if ($tunneledRange !== null && $clientRange !== '') {
    if ($clientRange !== $tunneledRange) {
        http_response_code(400);
        echo "Bad Request\n\nRange and X-Cors-Proxy-Range disagree";
        exit;
    }
    $tunneledRange = null;
}

$curlHeaders = kv_headers_to_curl_format(filter_request_headers($allHeaders));

// If Content-Type was wrapped, replace the placeholder
// application/octet-stream with the original value so the target
// server receives the correct Content-Type.
if (
    $originalContentType !== null &&
    !in_array('content-type', $connection_headers, true) &&
    !in_array('x-cors-proxy-content-type', $connection_headers, true)
) {
    $curlHeaders = array_values(array_filter(
        $curlHeaders,
        fn($h) => stripos($h, 'Content-Type:') !== 0
    ));
    $curlHeaders[] = 'Content-Type: ' . $originalContentType;
}

if (
    $tunneledRange !== null &&
    !in_array('range', $connection_headers, true) &&
    !in_array('x-cors-proxy-range', $connection_headers, true)
) {
    $curlHeaders = array_values(array_filter(
        $curlHeaders,
        fn($h) => stripos($h, 'Range:') !== 0
    ));
    $curlHeaders[] = 'Range: ' . $tunneledRange;
}

$has_range = !empty(array_filter(
    $curlHeaders,
    fn($h) => stripos($h, 'Range:') === 0
));
if ($has_range || $_SERVER['REQUEST_METHOD'] === 'HEAD') {
    $curlHeaders = array_values(array_filter(
        $curlHeaders,
        fn($h) => stripos($h, 'Accept-Encoding:') !== 0
    ));
    // A range addresses bytes of the encoded representation, so ask the
    // target for an unencoded one. This is always what the proxy's clients
    // need: browsers decode Content-Encoding automatically and can't decode
    // a slice from the middle of a compressed stream. The Fetch spec
    // therefore has browsers send Accept-Encoding: identity with Range
    // requests, and scripts can't override it. We set it again here because
    // a server in front of this script may rewrite Accept-Encoding before
    // the request gets here. As of 2026-09-26, WP Cloud rewrites it to
    // "gzip, br".
    //
    // HEAD asks for the unencoded body too. Clients use its Content-Length
    // to compute range offsets, so it must describe the same bytes the
    // ranges address.
    $curlHeaders[] = 'Accept-Encoding: identity';
}

curl_setopt(
    $ch,
    CURLOPT_HTTPHEADER,
    // cURL generates Host from the target URL, including its custom port.
    $curlHeaders
);

// Set options to stream data
curl_setopt($ch, CURLOPT_RETURNTRANSFER, false);
curl_setopt($ch, CURLOPT_FOLLOWLOCATION, false);
// Keep encoded representation bytes unchanged, so Content-Encoding and Content-Length
// still describe the relayed body. cURL continues to decode transfer framing (chunked).
curl_setopt($ch, CURLOPT_HTTP_CONTENT_DECODING, false);
curl_setopt($ch, CURLOPT_HTTP_TRANSFER_DECODING, true);
curl_setopt($ch, CURLOPT_HEADERFUNCTION, function ($curl, $header) use (
    $targetUrl,
    &$pending_response_headers,
    &$in_interim_response,
    &$response_headers_complete,
    &$has_transfer_encoding,
    &$is_chunked_response
) {
    global $proxy_headers;
    $len = strlen($header);
    // cURL delivers each status line, header block, and any trailers here.
    if (stripos($header, 'HTTP/') === 0) {
        $status_code = preg_match('#^HTTP/\S+\s+(\d{3})#', $header, $matches)
            ? (int) $matches[1]
            : curl_getinfo($curl, CURLINFO_HTTP_CODE);
        if ($status_code === 101) {
            replace_response_with_error(502, "Bad Gateway – the target switched protocols");
            exit;
        }
        $pending_response_headers = [];
        $has_transfer_encoding = false;
        $is_chunked_response = false;
        $response_headers_complete = false;
        $in_interim_response = $status_code < 200;
        if (!$in_interim_response) {
            http_response_code($status_code);
        }
        return $len;
    }
    if ($in_interim_response || $response_headers_complete) {
        // Interim fields and trailers must not become final response headers.
        return $len;
    }
    if (trim($header) === '') {
        $response_headers_complete = true;
        // We cannot relay encoded bytes after removing the metadata needed to
        // decode them. Such Connection nominations are invalid for content fields.
        if (in_array('content-encoding', connection_header_names($pending_response_headers), true)) {
            foreach ($pending_response_headers as $line) {
                [$name, $value] = explode(':', $line, 2);
                if (
                    strcasecmp(trim($name), 'Content-Encoding') === 0 &&
                    !in_array(strtolower(trim($value)), ['', 'identity'], true)
                ) {
                    replace_response_with_error(502, "Bad Gateway – hop-by-hop content encoding");
                    exit;
                }
            }
        }
        // A later Connection field may nominate an earlier field. Do not emit
        // anything upstream-owned until the entire block has been filtered.
        foreach (filter_response_headers($pending_response_headers, $proxy_headers) as $line) {
            [$name, $value] = explode(':', $line, 2);
            $name = strtolower(trim($name));
            $value = trim($value);
            if ($name === 'content-length') {
                // Transfer-Encoding overrides Content-Length regardless of field order.
                if ($has_transfer_encoding || !ctype_digit($value)) {
                    continue;
                }
                header('Content-Length: ' . $value);
            } elseif ($name === 'location') {
                header('Location: ' . rewrite_relative_redirect(
                    $targetUrl,
                    $value,
                    CURRENT_SCRIPT_URI
                ), true);
            } else {
                header($line, false);
            }
        }
        // cURL removes upstream chunk framing. Only the built-in server needs
        // manually generated downstream framing; production servers handle it.
        $is_chunked_response = $is_chunked_response &&
            $_SERVER['REQUEST_METHOD'] !== 'HEAD' &&
            !in_array(http_response_code(), [204, 304], true);
        if (should_send_as_chunked_response()) {
            header('Transfer-Encoding: chunked');
        }
        $pending_response_headers = [];
        return $len;
    }

    $parts = explode(':', $header, 2);
    if (count($parts) !== 2) {
        return $len;
    }
    $name = strtolower(trim($parts[0]));
    $value = trim($parts[1]);
    if ($name === 'content-length') {
        // Preserve the existing declared-size cap. Unknown-length responses are
        // streamed without a hard byte cap, and HEAD has no body to limit.
        if ($_SERVER['REQUEST_METHOD'] !== 'HEAD' && intval($value) >= MAX_RESPONSE_SIZE) {
            replace_response_with_error(413, "Response Too Large");
            exit;
        }
    }
    if ($name === 'transfer-encoding') {
        $has_transfer_encoding = true;
        $codings = array_map('trim', explode(',', strtolower($value)));
        $is_chunked_response = $is_chunked_response || in_array('chunked', $codings, true);
    }
    $pending_response_headers[] = trim($header);
    return $len;
});

curl_setopt($ch, CURLOPT_WRITEFUNCTION, function ($curl, $data) {
    send_response_chunk($data);
    return strlen($data);
});

// Handle request method and data
$requestMethod = $_SERVER['REQUEST_METHOD'];
curl_setopt($ch, CURLOPT_CUSTOMREQUEST, $requestMethod);
if ($requestMethod === 'HEAD') {
    // Otherwise curl waits for the body that Content-Length announces.
    curl_setopt($ch, CURLOPT_NOBODY, true);
}

if ($requestMethod !== 'GET' && $requestMethod !== 'HEAD' && $requestMethod !== 'OPTIONS') {
    // php://input is not available for multipart/form-data requests
    // because PHP parses the body into $_POST and $_FILES, consuming
    // the input stream. For such requests, we reconstruct the body
    // using CURLOPT_POSTFIELDS with CURLFile objects for any uploaded
    // files.
    $contentType = $_SERVER['CONTENT_TYPE'] ?? '';
    if (stripos($contentType, 'multipart/form-data') !== false && (!empty($_POST) || !empty($_FILES))) {
        $postFields = $_POST;
        foreach ($_FILES as $name => $fileInfo) {
            $postFields[$name] = new CURLFile(
                $fileInfo['tmp_name'],
                $fileInfo['type'] ?: 'application/octet-stream',
                $fileInfo['name']
            );
        }
        curl_setopt($ch, CURLOPT_POST, true);
        curl_setopt($ch, CURLOPT_POSTFIELDS, $postFields);
        // Content-Length was already filtered. Strip Content-Type too.
        // CURLOPT_POSTFIELDS with an array generates a new multipart
        // boundary, and we must let PHP curl set its own Content-Type
        // to match. The original Content-Type from the browser has a
        // different boundary that doesn't match the reconstructed body.
        $filteredHeaders = array_values(array_filter(
            $curlHeaders,
            fn($h) => stripos($h, 'Content-Type:') !== 0
        ));
        curl_setopt($ch, CURLOPT_HTTPHEADER, $filteredHeaders);
    } else {
        $input = fopen('php://input', 'r');
        curl_setopt($ch, CURLOPT_UPLOAD, true);
        curl_setopt($ch, CURLOPT_INFILE, $input);
        // PHP's server-validated input size applies only to this unchanged raw stream.
        // Leave unknown lengths unset so cURL generates chunked upload framing.
        if (isset($_SERVER['CONTENT_LENGTH']) && ctype_digit((string) $_SERVER['CONTENT_LENGTH'])) {
            curl_setopt($ch, CURLOPT_INFILESIZE, (int) $_SERVER['CONTENT_LENGTH']);
        }
    }
}

// Avoid stale, cached responses. This also keeps the WP Cloud edge cache
// from storing responses. Every range of a file shares one proxy URL, so a
// cached slice could be served for another range. The target's own
// Cache-Control is never relayed. This is set here, before the snapshot
// below, so the proxy's own error responses keep it too.
header('Cache-Control: no-cache');

// Everything queued so far belongs to the proxy's own response: the CORS
// headers, the headers above, and any set by the deployment. The proxy
// restores these when it replaces the target's response with an error.
$proxy_headers = headers_list();

// Execute cURL session
$target_failed_mid_response = false;
if (!curl_exec($ch)) {
    if (headers_sent()) {
        // Part of the target's response was already sent. An error message
        // appended now would look like part of the target's body, so end
        // the response instead.
        $target_failed_mid_response = true;
    } else {
        // Nothing was sent yet, though the target's headers may be queued.
        replace_response_with_error(
            502,
            "Bad Gateway – curl_exec error: " . curl_error($ch)
        );
    }
}
// Close cURL session
if (version_compare(PHP_VERSION, '8.5', '<')) {
    // curl_close is deprecated in PHP 8.5 and later.
    // See https://www.php.net/manual/en/migration85.deprecated.php#migration85.deprecated.curl
    curl_close($ch);
}

// Only send chunked transfer encoding footer if we're using chunked encoding.
// We need to manually send the footer when running in the PHP built-in server
// because, unlike apache or nginx, it won't handle that for us.
// Leave it off after a target failure so the client sees an incomplete
// response.
if (should_send_as_chunked_response() && !$target_failed_mid_response) {
    echo "0\r\n\r\n";
}
